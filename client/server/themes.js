/**
 * 主题表。`mixed` = 三个 IP 混在一起（人多了不容易撞词）。
 * 顺序即前端下拉框的顺序，`default` 是没有主题（通用词库，见 words.js）。
 */
const THEMES = {
  default: { id: 'default', name: '通用（什么都能画）', words: null },
  arknights: { id: 'arknights', name: '明日方舟', words: ARKNIGHTS },
  wuthering: { id: 'wuthering', name: '鸣潮', words: WUTHERING },
  bluearchive: { id: 'bluearchive', name: '碧蓝档案', words: BLUEARCHIVE },
  anime: { id: 'anime', name: '二次元混合（方舟+鸣潮+档案）', words: null }
};

/** 三个 IP 合起来（去重），给「混合」主题用 */
const ANIME_MIX = (function () {
  const seen = new Set();
  const out = [];
  [ARKNIGHTS, WUTHERING, BLUEARCHIVE].forEach(list => {
    list.forEach(w => {
      if (seen.has(w)) return;
      seen.add(w);
      out.push(w);
    });
  });
  return out;
})();

THEMES.anime.words = ANIME_MIX;

/** 给前端用的主题菜单（**只有名字，没有词**） */
function themeList() {
  return Object.keys(THEMES).map(k => ({ id: THEMES[k].id, name: THEMES[k].name }));
}

function hasTheme(id) { return !!(id && THEMES[id]); }

/**
 * 取某个主题的词表。`default` 返回 null —— 表示「用 words.js 的通用词库」，
 * 由调用方决定怎么兜底（这样通用词库和主题词库各自管各自的）。
 */
function wordsOf(id) {
  const t = THEMES[id];
  return t ? t.words : null;
}

/**
 * 主题词库自检：和通用词库同一套规矩 —— 必须是 2 字以上的中文。
 * 单字词在这类游戏里是硬错误：猜手只知道「一个字」，而且任何字与它的编辑距离
 * 都是 1，会不停误报「很接近了」。
 */
Object.keys(THEMES).forEach(k => {
  const list = THEMES[k].words;
  if (!list) return;
  const bad = list.filter(w => !/^[\u4e00-\u9fa5]{2,}$/.test(w));
  if (bad.length) {
    throw new Error('主题词库「' + THEMES[k].name + '」里有不合格的词（必须是 2 字以上的中文）：' + bad.join('、'));
  }
  const dup = list.filter((w, i) => list.indexOf(w) !== i);
  if (dup.length) {
    throw new Error('主题词库「' + THEMES[k].name + '」里有重复词：' + dup.join('、'));
  }
});

module.exports = { THEMES, ANIME_MIX, themeList, hasTheme, wordsOf };
