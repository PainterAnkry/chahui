const ANIME_LISTS = [ARKNIGHTS, WUTHERING, BLUEARCHIVE, GENSHIN, STARRAIL,
  ENDFIELD, TOUHOU, UMA, ZZZ, MONSTERHUNTER];

/** 全 IP 合起来（去重），给「混合」主题用 */
const ANIME_MIX = (function () {
  const seen = new Set();
  const out = [];
  ANIME_LISTS.forEach(list => {
    list.forEach(w => {
      if (seen.has(w)) return;
      seen.add(w);
      out.push(w);
    });
  });
  return out;
})();

THEMES.anime.words = ANIME_MIX;

/** 给前端用的主题菜单（**只有名字，没有词**） */
function themeList() {
  const builtin = Object.keys(THEMES).map(k => ({ id: THEMES[k].id, name: THEMES[k].name }));
  // 用户自定义的排在内置之后（它们是「额外加的」，不是主干）
  return builtin.concat(CT.list());
}

function hasTheme(id) {
  if (id && THEMES[id]) return true;
  return CT.has(id);
}

/**
 * 取某个主题的词表。`default` 返回 null —— 表示「用 words.js 的通用词库」，
 * 由调用方决定怎么兜底（这样通用词库和主题词库各自管各自的）。
 */
function wordsOf(id) {
  const t = THEMES[id];
  if (t) return t.words;
  // 用户自定义词库（存 server/data/themes.json）
  const custom = CT.wordsOf(id);
  return custom || null;
}

/** 某个主题的显示名（含自定义） */
function nameOf(id) {
  const t = THEMES[id];
  if (t) return t.name;
  return CT.nameOf(id) || '';
}

/**
 * 主题词库自检：和通用词库同一套规矩 —— 必须是 2 字以上的中文。
 * 单字词在这类游戏里是硬错误：猜手只知道「一个字」，而且任何字与它的编辑距离
 * 都是 1，会不停误报「很接近了」。
 */
Object.keys(THEMES).forEach(k => {
  const list = THEMES[k].words;
  if (!list) return;
  const bad = list.filter(w => !/^[\u4e00-\u9fa5]{2,}$/.test(w));
  if (bad.length) {
    throw new Error('主题词库「' + THEMES[k].name + '」里有不合格的词（必须是 2 字以上的中文）：' + bad.join('、'));
  }
  const dup = list.filter((w, i) => list.indexOf(w) !== i);
  if (dup.length) {
    throw new Error('主题词库「' + THEMES[k].name + '」里有重复词：' + dup.join('、'));
  }
});

